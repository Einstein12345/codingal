def function1(n):
    count=0
    print('the number entered by user is ',n)
    count+=1
    print("total iteration done by code is ",count)
function1(10)
function1(20)
print("with any n, time taken by the code wont change")
# analysis
# this is example of constant time complexity.it is represented by O(1)
# here the value of n entered by user will not affect the iterations
#so constant time complexity 
